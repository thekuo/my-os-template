// Turns an adaptive icon's three SVG layers into Android resources in overlay/ (run locally, commit the output):
//   node android/scripts/icons.mjs <dir with foreground.svg background.svg [monochrome.svg]>
// Writes, for every density: mipmap ic_launcher_{foreground,background,monochrome}_myos.png (108dp layers),
// legacy ic_launcher.png / ic_launcher_round.png (48dp, for Android < 8), the splash icon (240dp, the foreground's
// safe zone fills the 160dp splash circle), and the mipmap-anydpi-v26 adaptive XML. Needs Playwright's Chromium.
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pw = process.env.PW || join(execSync('npm root -g').toString().trim(), 'playwright');
const { chromium } = require(pw);

const src = process.argv[2];
if (!src || !existsSync(join(src, 'foreground.svg')) || !existsSync(join(src, 'background.svg'))) {
  console.error('usage: node android/scripts/icons.mjs <dir with foreground.svg and background.svg [monochrome.svg]>');
  process.exit(1);
}
const res = process.env.OUT || join(dirname(fileURLToPath(import.meta.url)), '..', 'overlay', 'app', 'src', 'main', 'res');
const svg = name => existsSync(join(src, name)) ? readFileSync(join(src, name), 'utf8') : null;
const fg = svg('foreground.svg'), bg = svg('background.svg'), mono = svg('monochrome.svg');
const uri = s => 'data:image/svg+xml;base64,' + Buffer.from(s).toString('base64');
const DENS = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

const browser = await chromium.launch();
const page = await browser.newPage();
// layers: list of svg strings stacked; box: output px; crop: fraction of the 108 canvas shown (1 = all, 72/108 = safe zone)
async function render(layers, box, { crop = 1, mask = null } = {}) {
  const full = Math.round(box / crop), off = Math.round((full - box) / 2);
  const radius = mask === 'circle' ? '50%' : mask === 'square' ? '18%' : '0';
  await page.setViewportSize({ width: box, height: box });
  await page.setContent(`<html><body style="margin:0;background:transparent">
    <div style="position:relative;width:${box}px;height:${box}px;overflow:hidden;border-radius:${radius}">
    ${layers.map(l => `<img src="${uri(l)}" style="position:absolute;left:${-off}px;top:${-off}px;width:${full}px;height:${full}px">`).join('')}
    </div></body></html>`);
  await page.waitForFunction(() => [...document.images].every(i => i.complete));
  return page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: box, height: box } });
}
const put = (dir, name, buf) => { mkdirSync(join(res, dir), { recursive: true }); writeFileSync(join(res, dir, name), buf); };

for (const [d, k] of Object.entries(DENS)) {
  const layer = Math.round(108 * k), legacy = Math.round(48 * k), splash = Math.round(240 * k);
  put(`mipmap-${d}`, 'ic_launcher_foreground_myos.png', await render([fg], layer));
  put(`mipmap-${d}`, 'ic_launcher_background_myos.png', await render([bg], layer));
  if (mono) put(`mipmap-${d}`, 'ic_launcher_monochrome_myos.png', await render([mono], layer));
  put(`mipmap-${d}`, 'ic_launcher.png', await render([bg, fg], legacy, { crop: 72 / 108, mask: 'square' }));
  put(`mipmap-${d}`, 'ic_launcher_round.png', await render([bg, fg], legacy, { crop: 72 / 108, mask: 'circle' }));
  put(`drawable-${d}`, 'myos_splash_icon.png', await render([fg], splash));
}
await browser.close();

// The PNG splash icon replaces the vector one (same resource name)
rmSync(join(res, 'drawable', 'myos_splash_icon.xml'), { force: true });
const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/scripts/icons.mjs from ${src} -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background_myos" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground_myos" />
${mono ? '    <monochrome android:drawable="@mipmap/ic_launcher_monochrome_myos" />\n' : ''}</adaptive-icon>
`;
put('mipmap-anydpi-v26', 'ic_launcher.xml', xml);
put('mipmap-anydpi-v26', 'ic_launcher_round.xml', xml);
console.log(`icons: wrote ${Object.keys(DENS).length} densities from ${src}${mono ? ' (with monochrome)' : ''}`);
